/**
 * Emit Typed DataModel profile JSON + CL++ IntelliSense header.
 */

import fs from "node:fs";
import path from "node:path";
import type { DatamodelNode, DatamodelProfile } from "./datamodel.js";
import { buildDatamodelProfile } from "./datamodel.js";

function safeIdent(name: string): string {
	const cleaned = name.replace(/[^A-Za-z0-9_]/g, "_");
	return /^[A-Za-z_]/.test(cleaned) ? cleaned : `_${cleaned}`;
}

function emitStruct(node: DatamodelNode, structName: string, depth: number): string {
	const pad = "\t".repeat(depth);
	const childEntries = Object.values(node.children);
	if (!childEntries.length) {
		return `${pad}// ${node.path} : ${node.className}\n`;
	}
	const lines: string[] = [];
	lines.push(`${pad}struct ${structName} {`);
	for (const child of childEntries.sort((a, b) => a.name.localeCompare(b.name))) {
		const field = safeIdent(child.name);
		const nested = `${structName}_${field}`;
		if (Object.keys(child.children).length) {
			lines.push(emitStruct(child, nested, depth + 1).trimEnd());
			lines.push(`${pad}\t${nested} ${field}; // ${child.className}`);
		} else {
			lines.push(`${pad}\t${child.className} ${field};`);
		}
	}
	lines.push(`${pad}};`);
	return lines.join("\n") + "\n";
}

export function generateDatamodelHeader(profile: DatamodelProfile): string {
	const body = emitStruct(profile.root, "Dm_DataModel", 0);
	return [
		"#pragma once",
		"// Generated by Cluaupp Typed DataModel — do not edit.",
		`// Project: ${profile.projectName} (${profile.projectJson})`,
		`// schemaVersion: ${profile.schemaVersion}`,
		"// IntelliSense / static check aid. Runtime remains Roblox FindFirstChild / WaitForChild.",
		"",
		body,
		"// Root mirror (optional binding for IntelliSense only):",
		"struct Dm_DataModel Dm;",
		"",
	].join("\n");
}

export function profileWithoutIndex(profile: DatamodelProfile): Omit<DatamodelProfile, "byPath"> & { paths: string[] } {
	const { byPath, ...rest } = profile;
	return { ...rest, paths: Object.keys(byPath).filter((p) => p !== "DataModel").sort() };
}

export function writeDatamodelArtifacts(
	projectRoot: string,
	opts?: { projectJson?: string; outDir?: string; headerPath?: string },
): { profile: DatamodelProfile; profilePath: string; headerPath: string } | null {
	const profile = buildDatamodelProfile(projectRoot, opts?.projectJson);
	if (!profile) {
		return null;
	}
	const outDir = opts?.outDir || path.join(projectRoot, ".cluaupp");
	fs.mkdirSync(outDir, { recursive: true });
	const profilePath = path.join(outDir, "datamodel-profile.json");
	fs.writeFileSync(profilePath, JSON.stringify(profileWithoutIndex(profile), null, "\t") + "\n", "utf8");

	const headerPath =
		opts?.headerPath ||
		path.join(projectRoot, "include", "clpp", "generated", "datamodel.clh");
	fs.mkdirSync(path.dirname(headerPath), { recursive: true });
	fs.writeFileSync(headerPath, generateDatamodelHeader(profile), "utf8");

	return { profile, profilePath, headerPath };
}
